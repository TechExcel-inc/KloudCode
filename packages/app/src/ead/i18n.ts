const dict: Record<Lang, Dict> = { en, zh, ja, ko }

export function t(lang: Lang, key: keyof Dict, vars?: Record<string, string | number>) {
  const bundle = dict[lang] ?? en
  let text = bundle[key] || en[key] || String(key)
  if (!vars) return text
  for (const [name, val] of Object.entries(vars)) {
    text = text.replace(new RegExp(`\\{\\{${name}\\}\\}`, "g"), String(val))
  }
  return text
}
